#!/usr/bin/env bash
# shellcheck disable=SC2034  # globals set here are read by the sourced libraries
# gen-answers.sh — answers.example, configure's questions as a blank answers
# file (docs/design-answers.md), generated from what configure itself reads:
# the schema's rows (lib/env.schema.tsv, services/*/env.tsv) — their meaning,
# type and recommended answer — and the services' labels (mediastack.desc,
# mediastack.preset, mediastack.installer, mediastack.arrtype). A new service
# folder appears in it by running this; CI fails while it is stale.
# Renders on a throwaway copy of the repo (tracked files only, your custom/
# never in it); needs `docker compose` (the standalone plugin renders without
# a daemon).
#
#   scripts/gen-answers.sh           rewrite answers.example
#   scripts/gen-answers.sh --check   exit 1 (with the diff) when it is stale
set -euo pipefail
cd "$(dirname "${BASH_SOURCE[0]}")/.."
repo=$PWD
mode=${1:-write}
[[ "$mode" == write || "$mode" == --check ]] || { echo "usage: scripts/gen-answers.sh [--check]" >&2; exit 2; }
work=$(mktemp -d); trap 'rm -rf "$work"' EXIT
git -C "$repo" ls-files -z | (cd "$repo" && xargs -0 cp --parents -t "$work")
cd "$work"
cp .env.example .env
sed '$d' mediastack.sh > .gen-answers-lib.sh
# shellcheck disable=SC1091
source ./.gen-answers-lib.sh
set +E; trap - ERR
vpn_gen >/dev/null
RENDERED_JSON=""; render

# describe KEY TYPE DEFAULT RECOMMENDED MEANING — the two comment lines above a key
describe() {
    local k=$1 t=$2 d=$3 r=$4 m=$5 choices rec
    case "$t" in
        enum:*) choices=${t#enum:}; choices=${choices//|/ | } ;;
        bool)   choices="true | false" ;;
        *)      choices=$(env_type_expect "$t") ;;
    esac
    [[ -z "${ANSWER_WORDS[$k]:-}" ]] || choices+=" (or ${ANSWER_WORDS[$k]})"
    case "$r" in
        ask)     rec="no recommendation — asked when it applies; with no terminal it must be written" ;;
        skip)    rec="optional: blank leaves it unset" ;;
        default) if [[ "$d" != - ]]; then rec="recommended: $d"
                 elif [[ -n "${ANSWER_WORDS[$k]:-}" ]]; then rec="recommended: ${ANSWER_WORDS[$k]}"
                 else rec="recommended: empty"; fi ;;
        =*)      rec="recommended: ${r#=}" ;;
        login)   rec="only with STACK_LOGINS=each, where blank asks it (generated otherwise, or STACK_PASSWORD's)" ;;
        *)       rec="recommended: $r" ;;
    esac
    [[ "$t" != secret ]] || rec+=" — a secret: keep this file yours alone (chmod 600)"
    printf '# %s\n#   %s — %s\n%s=\n' "$m" "$choices" "$rec" "$k"
}

# rows FILE — every row of one schema file configure asks (recommended is not -), in its order
rows() {
    local k t e w d r m
    while IFS=$'\t' read -r k t e w d r m; do
        [[ "$r" != - ]] || continue
        [[ "$k" == *'<'* ]] && continue                            # a family: expanded where it belongs
        [[ " CONFIGURE_MODE START SIGNIN " == *" $k "* ]] && continue   # written at the top
        [[ " $LOGIN_KEYS " == *" $k "* ]] && r=login
        echo; describe "$k" "$t" "$d" "$r" "$m"
    done < <(grep -vE '^(#|[[:space:]]*$)' "$1")
}
# the stack's own logins' passwords: asked only when each is typed
LOGIN_KEYS=$(for f in $(declare -F | awk '$3 ~ /^[a-z][a-z0-9_]*_logins$/ { print $3 }'); do "$f"; done | cut -f3 | tr '\n' ' ')

row_of() { awk -F'\t' -v k="$1" '$1 == k { print; exit }' lib/env.schema.tsv services/*/env.tsv; }   # the schema row of KEY

out=$work/answers.example
{
cat <<'EOT'
# answers.example — configure's questions, answered ahead (docs/design-answers.md).
# Generated by scripts/gen-answers.sh from the schema and the services' labels:
# change those, not this file.
#
# Copy it, answer what you want, leave the rest blank, keep it yours alone:
#   cp answers.example answers.env && chmod 600 answers.env
#   ./mediastack.sh install --answers answers.env      (or: configure --answers ...)
# A written answer is used. A blank one keeps what is already set; on a first
# install it takes the recommendation, or is asked — and with no terminal,
# an answer that would be asked must be written. Values follow .env's rules:
# no quotes, and no comment after a value (comments go on their own line).
# answers*.env is git-ignored: your answers never reach the repo.
EOT
echo; echo "# ---------------------------------------------------- how configure runs --"
for k in CONFIGURE_MODE START; do IFS=$'\t' read -r _ t _ _ d r m <<<"$(row_of "$k")"; echo; describe "$k" "$t" "$d" "$r" "$m"; done

echo; echo "# -------------------------------------------------------------- services --"
echo "# y runs it, n leaves it off. Answer one and the blank ones take the standard"
echo "# preset (on a re-run: what runs now); answer none and the question is asked."
echo "# --services a,b on the command line names the exact set instead."
std=" $(svc_managed_where mediastack.preset standard | tr '\n' ' ') "
for s in $(svc_managed); do
    [[ "$s" == wizarr || "$s" == authentik ]] && continue                    # SIGNIN picks these
    [[ -z "$(svc_label "$s" mediastack.installer)" ]] || continue             # set up by its own command
    printf '\n# %s\n#   y | n — recommended: %s\nENABLE_%s=\n' "$(svc_label "$s" mediastack.desc)" \
        "$( [[ "$std" == *" $s "* ]] && echo y || echo n )" "$(uvar "$s")"
done

echo; echo "# --------------------------------------------------- how people sign in --"
IFS=$'\t' read -r _ t _ _ d r m <<<"$(row_of SIGNIN)"; echo; describe SIGNIN "$t" "$d" "$r" "$m"

echo; echo "# -------------------------------------------------------------- the stack --"
rows lib/env.schema.tsv

for f in services/*/env.tsv; do
    s=${f#services/}; s=${s%/env.tsv}; [[ "$s" != _arr ]] || s="the arrs"
    body=$(rows "$f")
    if [[ "$s" == recyclarr ]]; then   # TRaSH's profile, one per arr it manages (an arr made for one profile carries it)
        IFS=$'\t' read -r _ t _ _ d r m <<<"$(row_of 'TRASH_PROFILE_<arr>')"
        for a in $(svc_managed); do
            [[ "$(svc_label "$a" mediastack.arrtype)" =~ ^(sonarr|radarr)$ && -z "$(svc_label "$a" mediastack.trashprofile)" ]] || continue
            body+=$'\n'"$(echo; describe "$(trash_envkey "$a")" "$t" "$d" "$r" "$m ($a)")"
        done
    fi
    [[ -n "$body" ]] || continue
    printf '\n# %s\n' "$(printf -- '-%.0s' {1..60}) $s --"
    printf '%s\n' "$body"
done
} > "$out"

if [[ "$mode" == --check ]]; then
    diff -u "$repo/answers.example" "$out" || { echo "answers.example is stale — run: scripts/gen-answers.sh, and commit it" >&2; exit 1; }
    echo "OK answers.example is current"
else
    cp "$out" "$repo/answers.example"
    echo "answers.example written ($(grep -c '=$' "$out") questions)"
fi
