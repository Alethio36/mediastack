#!/usr/bin/env bash
# services/traefik/edge.sh — the Traefik HTTPS edge: traefik_ensure (auto-run
# by up; its questions are in questions.sh), traefik_gen (generated static + dynamic config, the gate's
# middleware), each service's route labels (edge_route_labels, written into
# the VPN overlay by vpn_gen), and hostname and certificate re-setup (the
# traefik-setup verb). Nothing in lib/ writes Traefik's config or labels. Sourced by the entrypoint; relies on
# lib/common.sh and the entrypoint's service/render/inspect helpers at call
# time.

# ================================================================= traefik --
# Wave 3: the edge. All config is generated (desired state from .env); the
# only imperative act is issuing certs, which Traefik does itself.

traefik_ensure() { # traefik_ensure [--reconfigure]; runs on up/enable; idempotent
    svc_enabled traefik || return 0
    local miss
    if [[ "${1:-}" == --reconfigure ]]; then
        [[ -t 0 ]] || die "traefik-setup needs a terminal."
        hr "Traefik setup"; info "Enter keeps the value shown in [brackets]."
        # shellcheck disable=SC2034  # read by traefik_questions: every question asked
        local Q_MODE=full
        traefik_questions
    else
        # configure (or enable traefik) asks them: up never does
        miss=$(traefik_missing)
        [[ -z "$miss" ]] || die "$miss is not set — ./mediastack.sh configure asks it (or: ./mediastack.sh traefik-setup)"
    fi
    if certs_own; then own_cert_install; fi
    traefik_gen
}

traefik_missing() { # the first of Traefik's answers not recorded yet ("" when none is missing)
    local k keys=(STACK_DOMAIN ACME_EMAIL CF_DNS_API_TOKEN)
    if certs_own; then keys=(STACK_DOMAIN TLS_CERT_FILE TLS_KEY_FILE); fi
    for k in "${keys[@]}"; do [[ -n "$(env_get "$k")" ]] || { echo "$k"; return 0; }; done
}

traefik_gen() {
    local croot domain acmeenv caline hash duser dpass prehash posthash
    croot=$(env_get CONFIG_ROOT); domain=$(env_get STACK_DOMAIN)
    acmeenv=$(env_get ACME_ENV)
    # docker creates missing bind sources as root-owned DIRECTORIES; if the
    # container ever started before setup, our file paths are junk dirs now
    local f
    for f in "$croot/traefik/traefik.yml" "$croot/traefik/dynamic.yml" "$croot/traefik/dynamic/00-mediastack.yml"; do
        sudo test -d "$f" && { warn "removing docker-created junk directory at $f"; sudo rm -rf "$f"; }
    done
    sudo test -d /run-traefik-setup-first && sudo rm -rf /run-traefik-setup-first
    sudo install -d -m 700 "$croot/traefik" "$croot/traefik/acme" "$croot/traefik/certs"
    install -d -m 755 "$CUSTOM_DIR" "$PROXY_DIR"; repo_owned "$CUSTOM_DIR" "$PROXY_DIR"
    # env switch detection: staging certs must not survive into production
    # (and vice versa) — traefik would keep serving the cached ones forever
    local acme="$croot/traefik/acme/acme.json" stored=""
    if ! certs_own && sudo test -s "$acme"; then
        sudo grep -q "acme-staging" "$acme" && stored=staging || stored=production
        if [[ "$stored" != "$acmeenv" ]]; then
            warn "ACME_ENV is '$acmeenv' but stored certificates are '$stored' — resetting the certificate store so the switch takes effect (reissue happens automatically)."
            sudo mv "$acme" "$acme.old-$stored.$(date +%s)"
        fi
    fi
    # a fresh install has neither file yet: hash what exists (cat's miss is no
    # failure here — under pipefail it ended every first run; found by the snapshot test)
    prehash=$( { sudo cat "$croot/traefik/traefik.yml" "$croot/traefik/dynamic/00-mediastack.yml" 2>/dev/null || true; } | sha256sum)
    caline=""
    [[ "$acmeenv" == staging ]] && caline='      caServer: "https://acme-staging-v02.api.letsencrypt.org/directory"'
    # Let's Encrypt: the resolver, and the dashboard router asks it for the
    # wildcard; your own: Traefik's default certificate, from your files
    local resolver="" dashtls ownstore=""
    if certs_own; then
        dashtls='      tls: {}'
        ownstore='# your own certificate (TLS_SOURCE=own): every router is served it — none asks for one
tls:
  stores:
    default:
      defaultCertificate:
        certFile: /certs/fullchain.pem
        keyFile: /certs/privkey.pem'
    else
        resolver="certificatesResolvers:
  le:
    acme:
      email: $(env_get ACME_EMAIL)
      storage: /letsencrypt/acme.json
$caline
      dnsChallenge:
        provider: cloudflare
        resolvers:
          - \"1.1.1.1:53\"
          - \"8.8.8.8:53\""
        dashtls="      tls:
        certResolver: le
        domains:
          - main: \"$domain\"
            sans: [\"*.$domain\"]"
    fi
    local tmp; tmp=$(mktemp)
    cat > "$tmp" <<STATIC
# GENERATED by mediastack traefik-setup — DO NOT EDIT. Knobs live in .env.
ping: {}
api:
  dashboard: true
entryPoints:
  web:
    address: ":80"
    http:
      redirections:
        entryPoint:
          to: websecure
          scheme: https
  websecure:
    address: ":443"
providers:
  docker:
    exposedByDefault: false
    network: mediastack
  file:
    directory: /dynamic
    watch: true
$resolver
STATIC
    sudo install -m 600 "$tmp" "$croot/traefik/traefik.yml"
    duser=$(env_get TRAEFIK_DASH_USER); dpass=$(env_get TRAEFIK_DASH_PASSWORD)
    # deterministic salt: identical inputs must yield an identical file, or
    # the change-detection restart fires on every regeneration
    hash=$(openssl passwd -apr1 -salt "$(printf '%s' "$duser:$dpass" | sha256sum | cut -c1-8)" "$dpass")
    cat > "$tmp" <<DYNAMIC
# GENERATED by mediastack traefik-setup — DO NOT EDIT.
# The dashboard router is also the single wildcard-cert requester: every
# other router says tls=true and reuses the cert issued here.
http:
  routers:
    dashboard:
      rule: "Host(\`$(env_get TRAEFIK_DASH_HOST).$domain\`)"
      entryPoints: [websecure]
      service: api@internal
      middlewares: [$(signin_is authentik && echo mediastack-gate || echo dash-auth)]
$dashtls
  middlewares:
    dash-auth:
      basicAuth:
        users:
          - "$duser:$hash"
$(traefik_gate_middleware)
tcp:
  middlewares:
    # the LDAP route answers the stack network only — never the LAN
    mediastack-ldap-allow:
      ipAllowList:
        sourceRange: ["$(env_get MEDIASTACK_SUBNET)"]
DYNAMIC
    [[ -z "$ownstore" ]] || printf '%s\n' "$ownstore" >> "$tmp"
    sudo install -d -m 700 "$croot/traefik/dynamic"
    sudo rm -f "$croot/traefik/dynamic.yml"   # pre-dir layout leftover
    sudo install -m 600 "$tmp" "$croot/traefik/dynamic/00-mediastack.yml"; rm -f "$tmp"
    # user proxy hosts: copied in (applied on every up / traefik-setup)
    sudo rm -f "$croot/traefik/dynamic/"user-*.yml
    local uf n=0
    for uf in "$PROXY_DIR"/*.yml; do
        [[ -e "$uf" ]] || break
        sudo install -m 600 "$uf" "$croot/traefik/dynamic/user-$(basename "$uf")"; n=$((n+1))
    done
    (( n )) && info "$n user proxy file(s) from custom/proxy.d applied"
    ok "traefik config generated ($(traefik_cert_words), domain $domain)"
    # static config only loads at container start; a content change on a
    # running traefik needs an explicit restart or it silently stays stale
    posthash=$(sudo cat "$croot/traefik/traefik.yml" "$croot/traefik/dynamic/00-mediastack.yml" 2>/dev/null | sha256sum)
    if [[ "$prehash" != "$posthash" ]] \
        && sudo docker ps --format '{{.Names}}' 2>/dev/null | grep -x "$(svc_cname traefik)" >/dev/null; then
        info "config changed — restarting traefik to load it"
        # shellcheck disable=SC2034  # the inspect cache lives in the entrypoint (CACHE RULE at c_inspect)
        INSPECT_JSON=""
        sudo docker restart "$(svc_cname traefik)" >/dev/null \
            && ok "traefik restarted" \
            || wfail "traefik restart failed — restart it manually: sudo docker restart $(svc_cname traefik)"
    fi
}

traefik_gate_middleware() { # mediastack-gate: what a router with mediastack.auth=gate passes through
    # mediastack-strip: on every route that skips the gate — a client may never
    # set the headers the portal speaks with (an app that trusts them, like
    # Navidrome, would take any username it was sent)
    cat <<'STRIP'
    mediastack-strip:
      headers:
        customRequestHeaders:
          X-authentik-username: ""
          X-authentik-groups: ""
          X-authentik-email: ""
          X-authentik-name: ""
          X-authentik-uid: ""
STRIP
    if signin_is authentik; then
        # authentik's built-in outpost decides (services/authentik/authentik.sh attaches the gate to it)
        cat <<'GATE'
    mediastack-gate:
      forwardAuth:
        address: "http://authentik:9000/outpost.goauthentik.io/auth/traefik"
        trustForwardHeader: true
        authResponseHeaders:
          - X-authentik-username
          - X-authentik-groups
          - X-authentik-email
          - X-authentik-name
          - X-authentik-uid
GATE
    else
        # no portal (Wizarr mode): the route stays as it was — an accepted risk,
        # docs/roadmap.md (Security & access)
        cat <<'GATE'
    mediastack-gate:
      headers:
        customResponseHeaders:
          X-Mediastack-Gate: "off"
GATE
    fi
}

# hostname map is discovered from the fragments' own router labels
# (${X_HOST:-default}), so it self-maintains as services are added
traefik_host_vars() {
    grep -hoE '\$\{[A-Z0-9_]+_HOST:-[a-z0-9-]+\}' services/*/compose.yml \
        | sed -E 's/^\$\{([A-Z0-9_]+_HOST):-([a-z0-9-]+)\}$/\1 \2/' | sort -u
    echo "TRAEFIK_DASH_HOST dash"
}

cmd_traefik_hosts() {
    [[ -t 0 ]] || die "traefik-setup --hosts needs a terminal."
    local domain; domain=$(env_get STACK_DOMAIN)
    [[ -n "$domain" ]] || die "Run './mediastack.sh traefik-setup' first — no domain configured yet."
    hr "Service hostnames"
    explain "Pick each service's address" \
"Enter keeps the name shown in [brackets]. Names must be a single DNS
label: letters, numbers, hyphens (not first or last). The wildcard
certificate covers any choice — renames are free."
    local var def cur val
    local -A chosen
    # map on fd 3: ask() must keep stdin for the person's answers
    while read -r var def <&3; do
        cur=$(env_get "$var"); cur=${cur:-$def}
        while :; do
            ask HV "  ${var%_HOST} -> https://?.$domain" "$cur"; val="$REPLY_VAL"
            [[ "$val" =~ ^[a-z0-9]([a-z0-9-]*[a-z0-9])?$ ]] \
                || { warn "'$val' is not a valid DNS label — lowercase letters, numbers, hyphens only"; continue; }
            if [[ -n "${chosen[$val]:-}" ]]; then
                warn "'$val' is already taken by ${chosen[$val]} — pick another"
                continue
            fi
            break
        done
        chosen[$val]="${var%_HOST}"
        env_set "$var" "$val"
    done 3< <(traefik_host_vars)
    traefik_gen   # the dashboard hostname lives in the generated config
    info "Apply with: ./mediastack.sh up"
    info "(services whose name changed are recreated; renaming a VPN'd service recreates gluetun — a brief tunnel bounce)"
}

cmd_traefik_certs() { # where the certificate comes from: Let's Encrypt, your own files, or staging — applied end to end
    [[ -t 0 ]] || die "traefik-setup --certs needs a terminal."
    local acmef stored="(none issued yet)" rc=0
    acmef="$(env_get CONFIG_ROOT)/traefik/acme/acme.json"
    if sudo test -s "$acmef" 2>/dev/null; then
        sudo grep -q "acme-staging" "$acmef" && stored=staging || stored=production
    fi
    hr "Certificates"
    info "Now: $(traefik_cert_words) — Let's Encrypt's store holds: $stored"
    info "Switching is safe: a Let's Encrypt switch resets its store and reissues by itself."
    # shellcheck disable=SC2034  # read by the question: every answer offered
    local Q_MODE=full
    traefik_cert_question
    traefik_cert_specifics "$(env_get STACK_DOMAIN)" || rc=$?
    (( rc != 4 )) || die "that does not fit $(env_get STACK_DOMAIN) — nothing applied. To change the domain itself: ./mediastack.sh traefik-setup"
    if certs_own; then own_cert_install; fi
    traefik_gen
    # Jellyfin's LDAP checks the certificate only when it is trusted: follow the switch
    if signin_is authentik && svc_enabled jellyfin; then cmd_wire jellyfin; fi
}

cmd_traefik_setup() {
    svc_enabled traefik || die "traefik is not enabled. Enable it first: ./mediastack.sh enable traefik"
    if [[ "${1:-}" == --hosts ]]; then cmd_traefik_hosts; return; fi
    if [[ "${1:-}" == --certs ]]; then cmd_traefik_certs; return; fi
    traefik_ensure --reconfigure
    info "Apply with: ./mediastack.sh up   (recreates traefik if config changed)"
    info "Rename service addresses any time: ./mediastack.sh traefik-setup --hosts"
}

# ---- each service's routes, as Traefik labels (vpn_gen writes them into the
# overlay, on gluetun for a VPN'd service, on the service itself otherwise) ----
edge_enable_label() { echo "${1}traefik.enable: \"true\""; }   # edge_enable_label INDENT — the edge serves this container
edge_router_name() { echo "$1" | tr -cd 'a-z0-9'; }   # compose svc name -> traefik router name
edge_route_labels() {   # <indent> <rname> <sub> <cport> <stem> <auth> <bypass>  (router/service only)
    local i="$1" r="$2" sub="$3" cp="$4" stem="$5" auth="${6:-}" bypass="${7:-}"
    echo "${i}traefik.http.routers.${r}.rule: \"Host(\`\${${stem}_HOST:-${sub}}.\${STACK_DOMAIN:-unset.invalid}\`)\""
    echo "${i}traefik.http.routers.${r}.entrypoints: \"websecure\""
    echo "${i}traefik.http.routers.${r}.tls: \"true\""
    echo "${i}traefik.http.routers.${r}.service: \"${r}\""
    echo "${i}traefik.http.services.${r}.loadbalancer.server.port: \"${cp}\""
    # mediastack.auth: gate -> the portal decides who gets through (services/traefik/edge.sh
    # defines mediastack-gate: authentik's check when it runs, a no-op otherwise)
    if [[ "$auth" == gate ]]; then echo "${i}traefik.http.routers.${r}.middlewares: \"mediastack-gate@file\""; fi
    # mediastack.auth.bypass: a path (the API) that skips the gate — only for a
    # tool whose API demands its own key, so companion apps keep working. The
    # longer rule wins in Traefik, so this router takes that path.
    if [[ "$auth" == gate && -n "$bypass" ]]; then
        local p paths=""
        for p in $bypass; do paths+="${paths:+ || }PathPrefix(\`$p\`)"; done
        echo "${i}traefik.http.routers.${r}-api.rule: \"Host(\`\${${stem}_HOST:-${sub}}.\${STACK_DOMAIN:-unset.invalid}\`) && ($paths)\""
        echo "${i}traefik.http.routers.${r}-api.entrypoints: \"websecure\""
        echo "${i}traefik.http.routers.${r}-api.tls: \"true\""
        echo "${i}traefik.http.routers.${r}-api.service: \"${r}\""
        # a route past the gate never carries a username header a client made up
        echo "${i}traefik.http.routers.${r}-api.middlewares: \"mediastack-strip@file\""
    fi
}
